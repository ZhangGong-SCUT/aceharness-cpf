#!/usr/bin/env node
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const API_ROOT = process.env.GITCODE_API_ROOT || 'https://gitcode.com/api/v5';

function arg(name, fallback = '') {
  const index = process.argv.indexOf(name);
  if (index === -1 || index === process.argv.length - 1) return fallback;
  return process.argv[index + 1];
}

function parsePrUrl(url) {
  const match = String(url || '').match(/https?:\/\/[^/\s]+\/([^/\s]+)\/([^/\s]+)\/(?:pulls?|merge_requests)\/(\d+)/i);
  if (!match) return null;
  return { owner: match[1], repo: match[2].replace(/\.git$/i, ''), number: match[3] };
}

async function gitcodeGet(path, token) {
  const separator = path.includes('?') ? '&' : '?';
  const url = `${API_ROOT}${path}${token ? `${separator}access_token=${encodeURIComponent(token)}` : ''}`;
  const response = await fetch(url, { headers: { Accept: 'application/json' } });
  const text = await response.text();
  if (!response.ok) {
    if (response.status === 404) return [];
    throw new Error(`${response.status} ${url} ${text.slice(0, 300)}`);
  }
  try {
    return text ? JSON.parse(text) : [];
  } catch {
    return [];
  }
}

function looksLikeAiReview(item) {
  const login = String(item.user?.login || item.author?.username || '').toLowerCase();
  const body = String(item.body || '');
  if (/ai|bot|review|harness|codereview|检视/.test(login)) return true;
  if (/AI\s*检视|AI Review|AI评审|generated by|code review bot/i.test(body)) return true;
  if (item.path || item.diff_hunk || item.position) return true;
  return false;
}

function normalizeComment(item, source) {
  return {
    source,
    id: item.id || item.node_id || '',
    author: item.user?.login || item.author?.username || '',
    path: item.path || item.filename || '',
    line: item.line || item.original_line || '',
    body: String(item.body || '').trim(),
    html_url: item.html_url || item.url || '',
    ai_review: looksLikeAiReview(item),
  };
}

async function main() {
  const prUrl = arg('--pr-url');
  const parsed = parsePrUrl(prUrl);
  const owner = arg('--owner', parsed?.owner || '');
  const repo = arg('--repo', parsed?.repo || '');
  const number = arg('--number', parsed?.number || '');
  const outDir = resolve(arg('--out', 'outputs'));
  const token = arg('--token', process.env.GITCODE_TOKEN || process.env.ACE_GITCODE_TOKEN || '');

  if (!owner || !repo || !number) {
    throw new Error('缺少 owner/repo/number，或传入 --pr-url');
  }

  const [reviewComments, issueComments, reviews] = await Promise.all([
    gitcodeGet(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/pulls/${encodeURIComponent(number)}/comments`, token),
    gitcodeGet(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/issues/${encodeURIComponent(number)}/comments`, token),
    gitcodeGet(`/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/pulls/${encodeURIComponent(number)}/reviews`, token),
  ]);

  const comments = [
    ...(Array.isArray(reviewComments) ? reviewComments.map((item) => normalizeComment(item, 'diff')) : []),
    ...(Array.isArray(issueComments) ? issueComments.map((item) => normalizeComment(item, 'issue')) : []),
    ...(Array.isArray(reviews) ? reviews.map((item) => normalizeComment(item, 'review')) : []),
  ].filter((item) => item.body);

  const actionable = comments.filter((item) => item.ai_review || item.source === 'diff');
  const lines = [
    `# AI 检视意见 ${owner}/${repo}#${number}`,
    '',
    actionable.length ? `共 ${actionable.length} 条需按意见修改。` : '没有 AI 检视意见，无需按检视改代码。',
    '',
    ...actionable.flatMap((item, index) => [
      `## ${index + 1}. ${item.path || 'PR 评论'}${item.line ? `:${item.line}` : ''}`,
      `- 作者：${item.author || 'unknown'}`,
      '',
      item.body,
      '',
    ]),
  ];

  const artifact = {
    owner,
    repo,
    number,
    comment_count: comments.length,
    actionable_count: actionable.length,
    comments: actionable,
    fetched_at: new Date().toISOString(),
  };

  await mkdir(outDir, { recursive: true });
  await writeFile(resolve(outDir, 'ai-review-comments.json'), `${JSON.stringify(artifact, null, 2)}\n`, 'utf8');
  await writeFile(resolve(outDir, 'ai-review.md'), `${lines.join('\n')}\n`, 'utf8');
  process.stdout.write(`${JSON.stringify({
    ok: true,
    actionable_count: actionable.length,
    md_path: resolve(outDir, 'ai-review.md'),
  }, null, 2)}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.message || error}\n`);
  process.exit(1);
});
